const ENTRIES = RAW.map(([stem, de, ru, en]) => ({ stem: norm(stem), de, ru, en }));

/** Findet Begriffe im Text (Wortanfang, damit Beugungen/Komposita-Anfänge treffen). Max. `limit` Einträge, nach Häufigkeit. */
export function glossaryFor(text, limit = 14) {
  const p = ' ' + norm(text) + ' ';
  const out = [];
  for (const e of ENTRIES) {
    const key = ' ' + e.stem;
    let i = p.indexOf(key), n = 0;
    while (i !== -1 && n < 9) { n++; i = p.indexOf(key, i + 1); }
    if (n) out.push({ ...e, n });
  }
  out.sort((a, b) => b.n - a.n || b.stem.length - a.stem.length);
  return out.slice(0, limit);
}
